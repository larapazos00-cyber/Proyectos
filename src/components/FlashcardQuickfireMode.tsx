import React, { useState, useEffect, useMemo, useCallback } from 'react';
import {
  Zap,
  RotateCcw,
  CheckCircle2,
  HelpCircle,
  ArrowLeft,
  Flame,
  Layers,
  Eye,
  Sparkles,
  Award,
  Clock,
} from 'lucide-react';
import confetti from 'canvas-confetti';
import { Subject, Flashcard, ReviewQuality } from '../types';
import { getTodayLocalDateStr, addDaysToDateStr } from '../utils/dateUtils';

interface FlashcardQuickfireModeProps {
  subjects: Subject[];
  selectedSubjectId: string;
  onChangeSubject: (subjectId: string) => void;
  onUpdateSubject?: (updated: Subject) => void;
  onExitQuickfire: () => void;
}

interface SessionCardResult {
  cardId: string;
  question: string;
  conceptTag: string;
  quality: ReviewQuality;
  nextIntervalDays: number;
}

/**
 * Calcula las flashcards pendientes para hoy de una asignatura.
 * Si la asignatura aún no tiene flashcards manuales creadas, genera tarjetas rápidas automáticas
 * a partir de sus notas Cornell y temas para que siempre se pueda usar Quickfire.
 */
export function getSubjectQuickfireDeck(subject: Subject | undefined): {
  allCards: Flashcard[];
  pendingTodayCards: Flashcard[];
  isAutoGenerated: boolean;
} {
  if (!subject) {
    return { allCards: [], pendingTodayCards: [], isAutoGenerated: false };
  }

  const todayStr = getTodayLocalDateStr();
  const existingCards = subject.flashcards || [];

  if (existingCards.length > 0) {
    const pending = existingCards.filter(
      (fc) => !fc.nextReview || fc.nextReview <= todayStr
    );
    return {
      allCards: existingCards,
      pendingTodayCards: pending,
      isAutoGenerated: false,
    };
  }

  // Si la materia no tiene flashcards guardadas, sintetizar tarjetas de repaso rápido desde Cornell/Temas
  const synthesized: Flashcard[] = [];

  (subject.cornellNotes || []).forEach((note) => {
    note.cues.slice(0, 3).forEach((cue, idx) => {
      synthesized.push({
        id: `auto-cornell-${note.id}-${idx}`,
        topicId: note.topicId,
        question: cue,
        answer: note.summary || note.notes.slice(0, 260),
        conceptTag: note.title,
        interval: 1,
        repetitions: 0,
        easeFactor: 2.5,
        nextReview: todayStr,
      });
    });
  });

  (subject.topics || []).forEach((topic) => {
    synthesized.push({
      id: `auto-topic-${topic.id}`,
      topicId: topic.id,
      question: `¿Cuáles son los puntos clave y fundamentos de "${topic.title}"?`,
      answer: `${topic.description}${
        topic.subtopics && topic.subtopics.length > 0
          ? `\n\nSubtemas esenciales: ${topic.subtopics.join(' · ')}.`
          : ''
      }`,
      hint:
        topic.subtopics && topic.subtopics.length > 0
          ? `Pista: Incluye ${topic.subtopics.slice(0, 2).join(' y ')}`
          : undefined,
      conceptTag: topic.category || 'Temario Oficial',
      interval: 1,
      repetitions: 0,
      easeFactor: 2.5,
      nextReview: todayStr,
    });
  });

  return {
    allCards: synthesized,
    pendingTodayCards: synthesized,
    isAutoGenerated: true,
  };
}

export const FlashcardQuickfireMode: React.FC<FlashcardQuickfireModeProps> = ({
  subjects,
  selectedSubjectId,
  onChangeSubject,
  onUpdateSubject,
  onExitQuickfire,
}) => {
  const currentSubject =
    subjects.find((s) => s.id === selectedSubjectId) || subjects[0];

  const todayStr = getTodayLocalDateStr();

  const { allCards, pendingTodayCards, isAutoGenerated } = useMemo(
    () => getSubjectQuickfireDeck(currentSubject),
    [currentSubject]
  );

  // Modo del mazo: 'pending' (solo pendientes hoy) o 'all' (todas las flashcards de la asignatura)
  const [deckScope, setDeckScope] = useState<'pending' | 'all'>(() =>
    pendingTodayCards.length > 0 ? 'pending' : 'all'
  );

  // Cola activa de tarjetas fijada al iniciar/reiniciar la tanda para evitar que desaparezcan a mitad de sesión
  const [sessionQueue, setSessionQueue] = useState<Flashcard[]>(() =>
    pendingTodayCards.length > 0 ? pendingTodayCards : allCards
  );
  const [currentIndex, setCurrentIndex] = useState<number>(0);
  const [isFlipped, setIsFlipped] = useState<boolean>(false);
  const [showHint, setShowHint] = useState<boolean>(false);
  const [sessionResults, setSessionResults] = useState<SessionCardResult[]>([]);
  const [streak, setStreak] = useState<number>(0);
  const [sessionCompleted, setSessionCompleted] = useState<boolean>(false);
  const [sessionStartMs, setSessionStartMs] = useState<number>(() => Date.now());

  // Reiniciar cola al cambiar de asignatura o alcance del mazo
  const startNewQuickfireRun = useCallback(
    (scopeOverride?: 'pending' | 'all', customCards?: Flashcard[]) => {
      const targetScope = scopeOverride || deckScope;
      const sourceDeck = customCards
        ? customCards
        : targetScope === 'pending' && pendingTodayCards.length > 0
        ? pendingTodayCards
        : allCards;

      setSessionQueue(sourceDeck);
      setCurrentIndex(0);
      setIsFlipped(false);
      setShowHint(false);
      setSessionResults([]);
      setStreak(0);
      setSessionCompleted(false);
      setSessionStartMs(Date.now());
    },
    [deckScope, pendingTodayCards, allCards]
  );

  useEffect(() => {
    const nextScope = pendingTodayCards.length > 0 ? 'pending' : 'all';
    setDeckScope(nextScope);
    const sourceDeck =
      nextScope === 'pending' && pendingTodayCards.length > 0
        ? pendingTodayCards
        : allCards;
    setSessionQueue(sourceDeck);
    setCurrentIndex(0);
    setIsFlipped(false);
    setShowHint(false);
    setSessionResults([]);
    setStreak(0);
    setSessionCompleted(false);
    setSessionStartMs(Date.now());
  }, [currentSubject?.id]);

  const currentCard = sessionQueue[currentIndex];

  // Calificar tarjeta actual con algoritmo SM-2 y pasar inmediatamente a la siguiente
  const handleRateCard = useCallback(
    (quality: ReviewQuality) => {
      if (!currentCard || !currentSubject) return;

      const prevInterval = currentCard.interval || 1;
      const prevReps = currentCard.repetitions || 0;
      const prevEase = currentCard.easeFactor || 2.5;

      let nextInterval = 1;
      let nextReps = prevReps + 1;
      let nextEase = prevEase;

      if (quality === 'repetir') {
        nextInterval = 1;
        nextReps = 0;
        nextEase = Math.max(1.3, prevEase - 0.2);
      } else if (quality === 'dificil') {
        nextInterval = Math.max(1, Math.round(prevInterval * 1.2));
        nextEase = Math.max(1.3, prevEase - 0.15);
      } else if (quality === 'bien') {
        nextInterval =
          prevReps === 0 ? 1 : prevReps === 1 ? 3 : Math.round(prevInterval * prevEase);
      } else if (quality === 'facil') {
        nextInterval =
          prevReps === 0
            ? 3
            : prevReps === 1
            ? 7
            : Math.round(prevInterval * prevEase * 1.3);
        nextEase = Math.min(3.0, prevEase + 0.15);
      }

      const nextReviewDate =
        quality === 'repetir'
          ? todayStr
          : addDaysToDateStr(todayStr, nextInterval);

      const updatedCard: Flashcard = {
        ...currentCard,
        interval: nextInterval,
        repetitions: nextReps,
        easeFactor: Math.round(nextEase * 100) / 100,
        nextReview: nextReviewDate,
        lastScore: quality,
      };

      // Persistir en la asignatura si hay callback disponible
      if (onUpdateSubject) {
        const baseList =
          currentSubject.flashcards && currentSubject.flashcards.length > 0
            ? currentSubject.flashcards
            : allCards;

        const existsInList = baseList.some((c) => c.id === updatedCard.id);
        const updatedFlashcards = existsInList
          ? baseList.map((c) => (c.id === updatedCard.id ? updatedCard : c))
          : [...baseList, updatedCard];

        onUpdateSubject({
          ...currentSubject,
          flashcards: updatedFlashcards,
        });
      }

      const nextResults: SessionCardResult[] = [
        ...sessionResults,
        {
          cardId: currentCard.id,
          question: currentCard.question,
          conceptTag: currentCard.conceptTag,
          quality,
          nextIntervalDays: nextInterval,
        },
      ];
      setSessionResults(nextResults);

      if (quality === 'facil' || quality === 'bien') {
        setStreak((prev) => prev + 1);
      } else {
        setStreak(0);
      }

      if (currentIndex + 1 < sessionQueue.length) {
        setCurrentIndex((prev) => prev + 1);
        setIsFlipped(false);
        setShowHint(false);
      } else {
        setSessionCompleted(true);
        const goodCount = nextResults.filter(
          (r) => r.quality === 'facil' || r.quality === 'bien'
        ).length;
        if (nextResults.length > 0 && goodCount / nextResults.length >= 0.7) {
          confetti({ particleCount: 70, spread: 65 });
        }
      }
    },
    [
      currentCard,
      currentSubject,
      currentIndex,
      sessionQueue.length,
      sessionResults,
      todayStr,
      onUpdateSubject,
      allCards,
    ]
  );

  // Atajos de teclado rápidos: Espacio/Enter para voltear, 1-4 para calificar
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (sessionCompleted || !currentCard) return;
      if (
        document.activeElement?.tagName === 'INPUT' ||
        document.activeElement?.tagName === 'TEXTAREA' ||
        document.activeElement?.tagName === 'SELECT'
      ) {
        return;
      }

      if (e.code === 'Space' || e.code === 'Enter') {
        e.preventDefault();
        setIsFlipped((prev) => !prev);
      } else if (isFlipped) {
        if (e.key === '1') handleRateCard('repetir');
        else if (e.key === '2') handleRateCard('dificil');
        else if (e.key === '3') handleRateCard('bien');
        else if (e.key === '4') handleRateCard('facil');
      }
    };

    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [sessionCompleted, currentCard, isFlipped, handleRateCard]);

  const progressPct =
    sessionQueue.length > 0
      ? Math.round(((currentIndex + (sessionCompleted ? 1 : 0)) / sessionQueue.length) * 100)
      : 0;

  const elapsedSeconds = Math.max(
    1,
    Math.round((Date.now() - sessionStartMs) / 1000)
  );
  const avgSecondsPerCard =
    sessionResults.length > 0
      ? Math.round((elapsedSeconds / sessionResults.length) * 10) / 10
      : 0;

  return (
    <div className="max-w-3xl mx-auto space-y-5 animate-in fade-in duration-200">
      {/* Cabecera minimalista de Flashcard Quickfire (sin la interfaz completa del generador de cuestionarios) */}
      <div className="bg-gradient-to-r from-slate-900 via-indigo-950 to-slate-900 text-white p-5 rounded-2xl shadow-md border border-indigo-500/30 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div className="flex items-center gap-3 min-w-0">
          <div className="p-2.5 rounded-xl bg-amber-400/20 text-amber-300 ring-1 ring-amber-400/40 shrink-0">
            <Zap className="w-5 h-5 fill-amber-300" />
          </div>
          <div className="min-w-0">
            <div className="flex items-center gap-2 flex-wrap">
              <h3 className="text-base font-extrabold tracking-tight">
                Modo Flashcard Quickfire
              </h3>
              <span className="px-2 py-0.5 rounded-full bg-indigo-500/30 border border-indigo-400/40 text-[10px] font-bold uppercase tracking-wider text-indigo-200">
                Repaso Rápido sin Distracciones
              </span>
            </div>
            <p className="text-xs text-slate-300 truncate mt-0.5">
              Voltea y califica tus flashcards pendientes con un clic o usando el teclado (Espacio y teclas 1–4).
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2 shrink-0 self-start sm:self-center">
          {streak > 0 && (
            <div className="px-2.5 py-1.5 rounded-xl bg-amber-500/20 border border-amber-400/30 text-amber-300 text-xs font-bold inline-flex items-center gap-1 font-mono-numbers">
              <Flame className="w-3.5 h-3.5 fill-amber-400" />
              <span>Racha: {streak}</span>
            </div>
          )}

          <button
            type="button"
            onClick={onExitQuickfire}
            className="px-3.5 py-2 rounded-xl bg-white/10 hover:bg-white/20 text-white text-xs font-bold transition-colors cursor-pointer inline-flex items-center gap-1.5"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            <span>Volver a Cuestionarios</span>
          </button>
        </div>
      </div>

      {/* Barra de controles rápidos: Selector de asignatura + Filtro Pendientes Hoy vs Todo el mazo */}
      <div className="bg-white dark:bg-slate-900 p-4 rounded-2xl border border-slate-200 dark:border-slate-800 shadow-2xs flex flex-col sm:flex-row sm:items-center justify-between gap-3">
        <div className="flex items-center gap-2.5 flex-1 min-w-0">
          <label className="text-xs font-bold text-slate-600 dark:text-slate-300 shrink-0">
            Asignatura:
          </label>
          <select
            value={currentSubject?.id || ''}
            onChange={(e) => onChangeSubject(e.target.value)}
            className="flex-1 text-xs bg-slate-50 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-2 text-slate-900 dark:text-white font-bold focus:outline-none cursor-pointer truncate"
          >
            {subjects.map((sub) => {
              const deck = getSubjectQuickfireDeck(sub);
              return (
                <option key={sub.id} value={sub.id}>
                  {sub.name} ({deck.pendingTodayCards.length} pendientes hoy / {deck.allCards.length} tot.)
                </option>
              );
            })}
          </select>
        </div>

        <div className="flex items-center gap-1.5 bg-slate-100 dark:bg-slate-800 p-1 rounded-xl border border-slate-200/80 dark:border-slate-700 text-xs shrink-0">
          <button
            type="button"
            onClick={() => {
              setDeckScope('pending');
              startNewQuickfireRun('pending');
            }}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all cursor-pointer ${
              deckScope === 'pending'
                ? 'bg-white dark:bg-slate-900 text-indigo-700 dark:text-indigo-300 shadow-2xs font-bold'
                : 'text-slate-600 dark:text-slate-400 hover:text-slate-900'
            }`}
          >
            Pendientes hoy ({pendingTodayCards.length})
          </button>
          <button
            type="button"
            onClick={() => {
              setDeckScope('all');
              startNewQuickfireRun('all');
            }}
            className={`px-3 py-1.5 rounded-lg font-semibold transition-all cursor-pointer ${
              deckScope === 'all'
                ? 'bg-white dark:bg-slate-900 text-indigo-700 dark:text-indigo-300 shadow-2xs font-bold'
                : 'text-slate-600 dark:text-slate-400 hover:text-slate-900'
            }`}
          >
            Todas ({allCards.length})
          </button>
        </div>
      </div>

      {/* Tarjeta activa o Pantalla de Resumen Quickfire */}
      {!sessionCompleted && currentCard ? (
        <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200 dark:border-slate-800 shadow-sm p-6 sm:p-8 space-y-6">
          {/* Barra superior de progreso de la tanda */}
          <div className="space-y-2">
            <div className="flex items-center justify-between text-xs text-slate-500 dark:text-slate-400">
              <div className="flex items-center gap-2">
                <span className="font-mono-numbers font-extrabold text-slate-900 dark:text-white">
                  Flashcard {currentIndex + 1} de {sessionQueue.length}
                </span>
                <span>·</span>
                <span className="px-2.5 py-0.5 rounded-full bg-indigo-50 dark:bg-indigo-950/70 text-indigo-700 dark:text-indigo-300 font-bold text-[11px]">
                  {currentCard.conceptTag || 'Concepto Clave'}
                </span>
                {isAutoGenerated && (
                  <span className="px-2 py-0.5 rounded-full bg-emerald-50 dark:bg-emerald-950/60 text-emerald-700 dark:text-emerald-300 text-[10px] font-semibold">
                    Generada de Apuntes/Temario
                  </span>
                )}
              </div>

              <span className="font-mono-numbers font-bold text-indigo-600 dark:text-indigo-400">
                {progressPct}%
              </span>
            </div>

            <div className="w-full bg-slate-100 dark:bg-slate-800 h-2 rounded-full overflow-hidden">
              <div
                className="bg-gradient-to-r from-indigo-600 to-blue-500 h-full transition-all duration-300 rounded-full"
                style={{
                  width: `${Math.max(5, ((currentIndex + 1) / sessionQueue.length) * 100)}%`,
                }}
              />
            </div>
          </div>

          {/* Área interactiva de la Flashcard (Pregunta / Respuesta) */}
          <div
            onClick={() => setIsFlipped((prev) => !prev)}
            className={`min-h-[250px] sm:min-h-[280px] rounded-2xl border-2 p-6 sm:p-8 flex flex-col justify-between cursor-pointer transition-all select-none ${
              isFlipped
                ? 'bg-gradient-to-br from-indigo-50/70 via-white to-blue-50/50 dark:from-indigo-950/40 dark:via-slate-900 dark:to-slate-900 border-indigo-400 dark:border-indigo-600 shadow-xs'
                : 'bg-slate-50/70 dark:bg-slate-800/40 hover:bg-slate-50 dark:hover:bg-slate-800/70 border-slate-200 dark:border-slate-700 hover:border-indigo-300'
            }`}
          >
            <div className="flex items-center justify-between text-[11px] font-bold uppercase tracking-wider">
              <span
                className={
                  isFlipped
                    ? 'text-indigo-600 dark:text-indigo-400 flex items-center gap-1.5'
                    : 'text-slate-400 dark:text-slate-500 flex items-center gap-1.5'
                }
              >
                <Layers className="w-3.5 h-3.5" />
                <span>{isFlipped ? 'Respuesta / Definición' : 'Pregunta / Estímulo Activo'}</span>
              </span>

              <span className="text-slate-400 dark:text-slate-500 font-normal">
                {isFlipped ? 'Clic o Espacio para ver pregunta' : 'Clic o Espacio para revelar'}
              </span>
            </div>

            <div className="my-auto py-6 text-center space-y-4">
              {!isFlipped ? (
                <>
                  <h4 className="text-lg sm:text-xl font-bold text-slate-900 dark:text-white leading-relaxed max-w-xl mx-auto">
                    {currentCard.question}
                  </h4>

                  {currentCard.hint && (
                    <div className="pt-2">
                      {showHint ? (
                        <div
                          onClick={(e) => e.stopPropagation()}
                          className="inline-block px-3.5 py-2 rounded-xl bg-amber-50 dark:bg-amber-950/50 border border-amber-200 dark:border-amber-800 text-xs text-amber-900 dark:text-amber-200"
                        >
                          💡 <strong>Pista:</strong> {currentCard.hint}
                        </div>
                      ) : (
                        <button
                          type="button"
                          onClick={(e) => {
                            e.stopPropagation();
                            setShowHint(true);
                          }}
                          className="text-xs font-semibold text-amber-600 dark:text-amber-400 hover:underline cursor-pointer"
                        >
                          Mostrar pista
                        </button>
                      )}
                    </div>
                  )}
                </>
              ) : (
                <div className="space-y-3 max-w-xl mx-auto text-left sm:text-center">
                  <div className="text-xs font-semibold text-slate-400 dark:text-slate-500 line-clamp-1">
                    {currentCard.question}
                  </div>
                  <div className="text-base sm:text-lg font-bold text-slate-900 dark:text-white leading-relaxed whitespace-pre-line">
                    {currentCard.answer}
                  </div>
                </div>
              )}
            </div>

            <div className="flex items-center justify-center">
              {!isFlipped ? (
                <button
                  type="button"
                  onClick={(e) => {
                    e.stopPropagation();
                    setIsFlipped(true);
                  }}
                  className="px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-bold shadow-xs transition-all cursor-pointer inline-flex items-center gap-2"
                >
                  <Eye className="w-4 h-4" />
                  <span>Revelar Respuesta (Espacio)</span>
                </button>
              ) : (
                <span className="text-[11px] font-semibold text-indigo-600 dark:text-indigo-400">
                  ¿Qué tan bien recordabas esta respuesta? Selecciona una opción abajo (o pulsa 1–4):
                </span>
              )}
            </div>
          </div>

          {/* Botonera Quickfire de calificación SM-2 */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5">
            <button
              type="button"
              onClick={() => handleRateCard('repetir')}
              className="p-3 rounded-2xl border border-rose-200 dark:border-rose-800/80 bg-rose-50/70 hover:bg-rose-600 text-rose-900 hover:text-white dark:bg-rose-950/40 dark:text-rose-200 dark:hover:bg-rose-600 dark:hover:text-white transition-all cursor-pointer text-center group"
            >
              <div className="text-xs font-extrabold">1 · Repetir</div>
              <div className="text-[10px] opacity-80 mt-0.5 font-mono-numbers">
                Hoy (&lt;24h)
              </div>
            </button>

            <button
              type="button"
              onClick={() => handleRateCard('dificil')}
              className="p-3 rounded-2xl border border-amber-200 dark:border-amber-800/80 bg-amber-50/70 hover:bg-amber-500 text-amber-900 hover:text-white dark:bg-amber-950/40 dark:text-amber-200 dark:hover:bg-amber-500 dark:hover:text-white transition-all cursor-pointer text-center group"
            >
              <div className="text-xs font-extrabold">2 · Difícil</div>
              <div className="text-[10px] opacity-80 mt-0.5 font-mono-numbers">
                +{Math.max(1, Math.round((currentCard.interval || 1) * 1.2))}d
              </div>
            </button>

            <button
              type="button"
              onClick={() => handleRateCard('bien')}
              className="p-3 rounded-2xl border border-blue-200 dark:border-blue-800/80 bg-blue-50/70 hover:bg-blue-600 text-blue-900 hover:text-white dark:bg-blue-950/40 dark:text-blue-200 dark:hover:bg-blue-600 dark:hover:text-white transition-all cursor-pointer text-center group"
            >
              <div className="text-xs font-extrabold">3 · Bien</div>
              <div className="text-[10px] opacity-80 mt-0.5 font-mono-numbers">
                +
                {(currentCard.repetitions || 0) === 0
                  ? 1
                  : (currentCard.repetitions || 0) === 1
                  ? 3
                  : Math.round((currentCard.interval || 1) * (currentCard.easeFactor || 2.5))}
                d
              </div>
            </button>

            <button
              type="button"
              onClick={() => handleRateCard('facil')}
              className="p-3 rounded-2xl border border-emerald-200 dark:border-emerald-800/80 bg-emerald-50/70 hover:bg-emerald-600 text-emerald-900 hover:text-white dark:bg-emerald-950/40 dark:text-emerald-200 dark:hover:bg-emerald-600 dark:hover:text-white transition-all cursor-pointer text-center group"
            >
              <div className="text-xs font-extrabold">4 · Fácil</div>
              <div className="text-[10px] opacity-80 mt-0.5 font-mono-numbers">
                +
                {(currentCard.repetitions || 0) === 0
                  ? 3
                  : (currentCard.repetitions || 0) === 1
                  ? 7
                  : Math.round(
                      (currentCard.interval || 1) * (currentCard.easeFactor || 2.5) * 1.3
                    )}
                d
              </div>
            </button>
          </div>
        </div>
      ) : (
        /* Pantalla de Resumen al completar la tanda Quickfire */
        <div className="bg-white dark:bg-slate-900 rounded-3xl border border-slate-200 dark:border-slate-800 shadow-sm p-6 sm:p-8 text-center space-y-6">
          <div className="w-14 h-14 rounded-2xl bg-indigo-50 dark:bg-indigo-950/70 text-indigo-600 dark:text-indigo-400 mx-auto flex items-center justify-center">
            <Award className="w-7 h-7" />
          </div>

          <div className="space-y-1">
            <h4 className="text-xl font-bold text-slate-900 dark:text-white">
              ¡Sesión Flashcard Quickfire Completada!
            </h4>
            <p className="text-xs text-slate-500 dark:text-slate-400">
              Has repasado {sessionResults.length} flashcards de{' '}
              <strong className="text-slate-800 dark:text-slate-200">
                {currentSubject?.name}
              </strong>{' '}
              en modo de alta velocidad.
            </p>
          </div>

          {/* KPIs de la tanda Quickfire */}
          <div className="grid grid-cols-3 gap-3 max-w-lg mx-auto text-xs">
            <div className="p-3.5 rounded-2xl bg-emerald-50/70 dark:bg-emerald-950/40 border border-emerald-200 dark:border-emerald-800">
              <span className="text-[10px] font-bold uppercase text-emerald-700 dark:text-emerald-300 block">
                Dominadas (Bien/Fácil)
              </span>
              <span className="text-2xl font-extrabold font-mono-numbers text-emerald-800 dark:text-emerald-200 mt-1 block">
                {
                  sessionResults.filter(
                    (r) => r.quality === 'facil' || r.quality === 'bien'
                  ).length
                }{' '}
                / {sessionResults.length}
              </span>
            </div>

            <div className="p-3.5 rounded-2xl bg-amber-50/70 dark:bg-amber-950/40 border border-amber-200 dark:border-amber-800">
              <span className="text-[10px] font-bold uppercase text-amber-700 dark:text-amber-300 block">
                A reforzar
              </span>
              <span className="text-2xl font-extrabold font-mono-numbers text-amber-800 dark:text-amber-200 mt-1 block">
                {
                  sessionResults.filter(
                    (r) => r.quality === 'repetir' || r.quality === 'dificil'
                  ).length
                }
              </span>
            </div>

            <div className="p-3.5 rounded-2xl bg-indigo-50/70 dark:bg-indigo-950/40 border border-indigo-200 dark:border-indigo-800">
              <span className="text-[10px] font-bold uppercase text-indigo-700 dark:text-indigo-300 block">
                Ritmo medio
              </span>
              <span className="text-2xl font-extrabold font-mono-numbers text-indigo-800 dark:text-indigo-200 mt-1 block">
                {avgSecondsPerCard}s
              </span>
            </div>
          </div>

          {/* Botones de acción tras finalizar */}
          <div className="flex flex-wrap items-center justify-center gap-3 pt-2">
            {sessionResults.some(
              (r) => r.quality === 'repetir' || r.quality === 'dificil'
            ) && (
              <button
                type="button"
                onClick={() => {
                  const weakIds = new Set(
                    sessionResults
                      .filter(
                        (r) => r.quality === 'repetir' || r.quality === 'dificil'
                      )
                      .map((r) => r.cardId)
                  );
                  const weakCards = allCards.filter((c) => weakIds.has(c.id));
                  if (weakCards.length > 0) {
                    startNewQuickfireRun(deckScope, weakCards);
                  }
                }}
                className="px-4 py-2.5 rounded-xl bg-amber-500 hover:bg-amber-600 text-white text-xs font-bold shadow-xs transition-colors cursor-pointer inline-flex items-center gap-1.5"
              >
                <RotateCcw className="w-3.5 h-3.5" />
                <span>Repasar solo las falladas / difíciles</span>
              </button>
            )}

            <button
              type="button"
              onClick={() => startNewQuickfireRun('all')}
              className="px-4 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-bold shadow-xs transition-colors cursor-pointer inline-flex items-center gap-1.5"
            >
              <Zap className="w-3.5 h-3.5" />
              <span>Repasar todo el mazo ({allCards.length})</span>
            </button>

            <button
              type="button"
              onClick={onExitQuickfire}
              className="px-4 py-2.5 rounded-xl bg-slate-100 hover:bg-slate-200 dark:bg-slate-800 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-200 text-xs font-bold transition-colors cursor-pointer"
            >
              Volver al Generador de Cuestionarios
            </button>
          </div>
        </div>
      )}
    </div>
  );
};
